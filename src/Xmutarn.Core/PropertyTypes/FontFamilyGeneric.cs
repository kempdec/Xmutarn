namespace KempDec.Xmutarn.Core.PropertyTypes;

/// <summary>
/// Representa as famílias genéricas de fonte do CSS (<c>font-family</c>).
/// </summary>
public enum FontFamilyGeneric
{
    /// <summary>
    /// Fonte com serifa.
    /// </summary>
    Serif,

    /// <summary>
    /// Fonte sem serifa.
    /// </summary>
    SansSerif,

    /// <summary>
    /// Fonte monoespaçada.
    /// </summary>
    Monospace,

    /// <summary>
    /// Fonte manuscrita.
    /// </summary>
    Cursive,

    /// <summary>
    /// Fonte decorativa ou fantasia.
    /// </summary>
    Fantasy,

    /// <summary>
    /// Fonte do sistema operacional.
    /// </summary>
    SystemUi,

    /// <summary>
    /// Fonte com serifa baseada na interface do sistema.
    /// </summary>
    UiSerif,

    /// <summary>
    /// Fonte sem serifa baseada na interface do sistema.
    /// </summary>
    UiSansSerif,

    /// <summary>
    /// Fonte monoespaçada baseada na interface do sistema.
    /// </summary>
    UiMonospace,

    /// <summary>
    /// Fonte arredondada baseada na interface do sistema.
    /// </summary>
    UiRounded,

    /// <summary>
    /// Fonte utilizada para expressões matemáticas.
    /// </summary>
    Math,

    /// <summary>
    /// Fonte estilizada tradicional chinesa utilizada para textos formais.
    /// </summary>
    Fangsong
}
