namespace KempDec.Xmutarn.Core.PropertyTypes;

/// <summary>
/// Representa os valores predefinidos para a propriedade CSS <c>font-size</c>.
/// </summary>
public enum FontSizeType
{
    /// <summary>
    /// Tamanho extra extra pequeno.
    /// </summary>
    XxSmall,

    /// <summary>
    /// Tamanho extra pequeno.
    /// </summary>
    XSmall,

    /// <summary>
    /// Tamanho pequeno.
    /// </summary>
    Small,

    /// <summary>
    /// Tamanho médio padrão.
    /// </summary>
    Medium,

    /// <summary>
    /// Tamanho grande.
    /// </summary>
    Large,

    /// <summary>
    /// Tamanho extra grande.
    /// </summary>
    XLarge,

    /// <summary>
    /// Tamanho extra extra grande.
    /// </summary>
    XxLarge,

    /// <summary>
    /// Tamanho menor relativo ao elemento pai.
    /// </summary>
    Smaller,

    /// <summary>
    /// Tamanho maior relativo ao elemento pai.
    /// </summary>
    Larger
}
